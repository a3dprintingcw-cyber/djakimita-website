const LANGS = ['en' => 'EN', 'nl' => 'NL', 'pap' => 'PAP'];

function current_lang(): string
{
    static $lang = null;
    if ($lang !== null) {
        return $lang;
    }
    $req = $_GET['lang'] ?? null;
    if ($req && isset(LANGS[$req])) {
        $lang = $req;
        if (PHP_SAPI !== 'cli' && !headers_sent()) {
            setcookie('lang', $lang, ['expires' => time() + 31536000, 'path' => '/', 'samesite' => 'Lax']);
        }
        return $lang;
    }
    $cookie = $_COOKIE['lang'] ?? '';
    if (isset(LANGS[$cookie])) {
        return $lang = $cookie;
    }
    $accept = strtolower($_SERVER['HTTP_ACCEPT_LANGUAGE'] ?? '');
    if (str_starts_with($accept, 'nl')) {
        return $lang = 'nl';
    }
    if (str_starts_with($accept, 'pap')) {
        return $lang = 'pap';
    }
    return $lang = 'en';
}

function t(string $key, array $vars = []): string
{
    static $all = null;
    if ($all === null) {
        $all = translations();
        foreach (['translations_checkout', 'translations_verify', 'translations_account', 'translations_pages', 'translations_faq', 'translations_legal'] as $fn) {
            if (function_exists($fn)) {
                foreach ($fn() as $l => $strings) {
                    $all[$l] = array_merge($all[$l], $strings);
                }
            }
        }
    }
    $text = $all[current_lang()][$key] ?? $all['en'][$key] ?? $key;
    foreach ($vars as $k => $v) {
        $text = str_replace('{' . $k . '}', (string) $v, $text);
    }
    return $text;
}

